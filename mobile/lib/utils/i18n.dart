  static String t(String key, [String? langCode]) {
    final lang = (langCode ?? 'en').toLowerCase();
    final dict = translations[lang] ?? translations['en']!;
    return dict[key] ?? translations['en']![key] ?? key;
  }
}

extension I18nExtension on BuildContext {
  String tr(String key) {
    try {
      final auth = read<AuthState>();
      final lang = auth.user?['native_language']?.toString();
      return AppI18n.t(key, lang);
    } catch (_) {
      return AppI18n.t(key, 'en');
    }
  }
}
