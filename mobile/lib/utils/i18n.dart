  static String _lookup(String key, String lang) {
    return translations[lang]?[key] ??
        extra[lang]?[key] ??
        translations['en']![key] ??
        extra['en']![key] ??
        key;
  }

  static String t(String key, [String? langCode, Map<String, Object?>? vars]) {
    final lang = (langCode ?? 'en').toLowerCase();
    var out = _lookup(key, lang);
    if (vars != null) {
      vars.forEach((k, v) {
        out = out.replaceAll('{$k}', '$v');
      });
    }
    return out;
  }

  /// `{base}_one` for n == 1, otherwise `{base}_other`, with `{n}` filled in.
  static String plural(String base, int n, [String? langCode]) {
    return t(n == 1 ? '${base}_one' : '${base}_other', langCode, {'n': n});
  }
}

extension I18nExtension on BuildContext {
  String? get _homeLang {
    try {
      return read<AuthState>().user?['native_language']?.toString();
    } catch (_) {
      return null;
    }
  }

  String tr(String key, [Map<String, Object?>? vars]) => AppI18n.t(key, _homeLang, vars);

  String trPlural(String base, int n) => AppI18n.plural(base, n, _homeLang);
}
