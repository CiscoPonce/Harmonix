export function getTranslation(key: string, langCode?: string | null, vars?: Vars): string {
  const code = (langCode || 'en').toLowerCase() as LanguageCode;
  const dict = TRANSLATIONS[code] || TRANSLATIONS.en;
  return interpolate(dict[key] || TRANSLATIONS.en[key] || key, vars);
}

/** "{n} day" / "{n} days" style plural pick; languages here all share the 1-vs-many rule. */
export function getPlural(baseKey: string, n: number, langCode?: string | null): string {
  const key = n === 1 ? `${baseKey}_one` : `${baseKey}_other`;
  return getTranslation(key, langCode, { n });
}
